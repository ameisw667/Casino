    END IF;
  END LOOP;

  SELECT array_agg(id) INTO v_dead_letter_ids
  FROM (
    SELECT id
    FROM public.wallet_events
    WHERE event_type = 'big_win_notify'
      AND processed_at IS NULL
      AND (attempts >= 5 OR dispatch_attempts >= 5)
      AND dead_letter_alerted_at IS NULL
    ORDER BY created_at
    LIMIT 200
    FOR UPDATE SKIP LOCKED
  ) AS unreported;

  PERFORM public.alert_wallet_event_dead_letters('big_win_events_retry', v_dead_letter_ids);
END;
$$;

