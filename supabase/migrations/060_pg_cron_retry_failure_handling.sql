-- 6.0 Background Jobs: bounded retry state for daily pg_cron wrappers and
-- deduplicated terminal alerts. This migration is additive; it does not run or deploy jobs.
-- Retry contract: three total attempts per (job_name, run_key), with 5m then 15m backoff.
-- Daily race uses the prior UTC day as its run_key, so retries preserve its existing
-- idempotency anchor in public.daily_races rather than settling the next day by accident.

CREATE TABLE IF NOT EXISTS public.background_job_runs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  job_name TEXT NOT NULL
    CHECK (job_name IN ('guide_telemetry_purge', 'bet_fingerprint_purge', 'daily_race_settlement')),
  run_key DATE NOT NULL,
  status TEXT NOT NULL DEFAULT 'retry_scheduled'
    CHECK (status IN ('retry_scheduled', 'succeeded', 'dead_letter')),
  attempt_count SMALLINT NOT NULL DEFAULT 0 CHECK (attempt_count BETWEEN 0 AND 3),
  first_started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  last_started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  next_attempt_at TIMESTAMPTZ,
  completed_at TIMESTAMPTZ,
  last_error TEXT,
  alert_enqueued_at TIMESTAMPTZ,
  UNIQUE (job_name, run_key)
);

ALTER TABLE public.background_job_runs ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.background_job_runs FROM PUBLIC, anon, authenticated;

-- The table is intentionally only accessed by the server-only functions below. An index is
-- omitted: at most three daily rows are inserted per day, so the unique key is sufficient.

CREATE OR REPLACE FUNCTION public.enqueue_cron_alert(p_job_name TEXT, p_error TEXT)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, net, vault, pg_temp
AS $$
DECLARE
  v_alert_secret TEXT;
BEGIN
  SELECT decrypted_secret INTO v_alert_secret
  FROM vault.decrypted_secrets
  WHERE name = 'cron_alert_secret'
  LIMIT 1;

  IF v_alert_secret IS NULL THEN
    RETURN false;
  END IF;

  PERFORM net.http_post(
    url := 'https://casino-xi-six.vercel.app/api/internal/cron-alert',
    headers := jsonb_build_object(
      'Content-Type', 'application/json',
      'x-cron-alert-secret', v_alert_secret
    ),
    body := jsonb_build_object(
      'job', left(p_job_name, 128),
      'error', left(p_error, 500)
    )
  );

  -- pg_net only confirms enqueueing the request. The durable terminal state remains queryable
  -- even if the downstream HTTP receiver is unavailable.
  RETURN true;
EXCEPTION WHEN OTHERS THEN
  RETURN false;
END;
$$;

REVOKE ALL ON FUNCTION public.enqueue_cron_alert(TEXT, TEXT) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.enqueue_cron_alert(TEXT, TEXT) TO service_role;

CREATE OR REPLACE FUNCTION public.execute_background_job(p_job_name TEXT, p_run_key DATE)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_attempt SMALLINT;
  v_delay INTERVAL;
  v_error TEXT;
  v_alert_enqueued BOOLEAN;
BEGIN
  -- A second pg_cron worker observes the same due row but never waits behind this run.
  IF NOT pg_try_advisory_xact_lock(
    hashtextextended('background_job:' || p_job_name || ':' || p_run_key::TEXT, 0)
  ) THEN
    RETURN;
  END IF;

  INSERT INTO public.background_job_runs (
    job_name,
    run_key,
    status,
    attempt_count,
    first_started_at,
    last_started_at
  )
  VALUES (p_job_name, p_run_key, 'retry_scheduled', 1, now(), now())
  ON CONFLICT (job_name, run_key) DO UPDATE
  SET
    attempt_count = public.background_job_runs.attempt_count + 1,
    last_started_at = now(),
    last_error = NULL,
    next_attempt_at = NULL
  WHERE public.background_job_runs.status = 'retry_scheduled'
    AND public.background_job_runs.attempt_count < 3
    AND (public.background_job_runs.next_attempt_at IS NULL
      OR public.background_job_runs.next_attempt_at <= now())
  RETURNING attempt_count INTO v_attempt;

  IF NOT FOUND THEN
    RETURN;
  END IF;

  BEGIN
    CASE p_job_name
      WHEN 'guide_telemetry_purge' THEN
        PERFORM public.purge_guide_telemetry_events();
      WHEN 'bet_fingerprint_purge' THEN
        PERFORM public.purge_bet_network_fingerprints();
      WHEN 'daily_race_settlement' THEN
        -- The final date-bound declaration below replaces this compatibility definition.
        -- Keep this initial body resolvable while the migration creates the DATE overload.
        PERFORM public.settle_daily_race();
      ELSE
        RAISE EXCEPTION 'Unsupported background job %', p_job_name;
    END CASE;

    UPDATE public.background_job_runs
    SET
      status = 'succeeded',
      completed_at = now(),
      next_attempt_at = NULL,
      last_error = NULL
    WHERE job_name = p_job_name AND run_key = p_run_key;
  EXCEPTION WHEN OTHERS THEN
    v_error := left(SQLERRM, 500);

    IF v_attempt < 3 THEN
      v_delay := CASE v_attempt
        WHEN 1 THEN interval '5 minutes'
        WHEN 2 THEN interval '15 minutes'
      END;

      UPDATE public.background_job_runs
      SET
        status = 'retry_scheduled',
        next_attempt_at = now() + v_delay,
        last_error = v_error
      WHERE job_name = p_job_name AND run_key = p_run_key;
    ELSE
      UPDATE public.background_job_runs
      SET
        status = 'dead_letter',
        completed_at = now(),
        next_attempt_at = NULL,
        last_error = v_error
      WHERE job_name = p_job_name
        AND run_key = p_run_key
      RETURNING alert_enqueued_at IS NULL INTO v_alert_enqueued;

      -- A terminal lifecycle enqueues at most one Sentry alert. If pg_net cannot enqueue the
      -- request, alert_enqueued_at stays NULL for manual inspection instead of claiming delivery.
      IF COALESCE(v_alert_enqueued, false)
        AND public.enqueue_cron_alert(p_job_name, v_error) THEN
        UPDATE public.background_job_runs
        SET alert_enqueued_at = now()
        WHERE job_name = p_job_name
          AND run_key = p_run_key
          AND alert_enqueued_at IS NULL;
      END IF;
    END IF;
  END;
END;
$$;

REVOKE ALL ON FUNCTION public.execute_background_job(TEXT, DATE) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.execute_background_job(TEXT, DATE) TO service_role;

CREATE OR REPLACE FUNCTION public.retry_failed_background_jobs()
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_run RECORD;
BEGIN
  FOR v_run IN
    SELECT job_name, run_key
    FROM public.background_job_runs
    WHERE status = 'retry_scheduled'
      AND next_attempt_at IS NOT NULL
      AND next_attempt_at <= now()
      AND attempt_count < 3
    ORDER BY next_attempt_at ASC
    LIMIT 20
  LOOP
    PERFORM public.execute_background_job(v_run.job_name, v_run.run_key);
  END LOOP;
END;
$$;

