CREATE OR REPLACE FUNCTION public.alert_wallet_event_dead_letters(
  p_job_name TEXT,
  p_event_ids UUID[]
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
  IF COALESCE(array_length(p_event_ids, 1), 0) = 0 THEN
    RETURN;
  END IF;

  IF public.enqueue_cron_alert(
    p_job_name,
    array_length(p_event_ids, 1) || ' wallet_events reached their retry limit'
  ) THEN
    UPDATE public.wallet_events
    SET dead_letter_alerted_at = now()
    WHERE id = ANY(p_event_ids)
      AND processed_at IS NULL
      AND dead_letter_alerted_at IS NULL;
  END IF;
END;
$$;

