CREATE OR REPLACE FUNCTION public.settle_daily_race(p_race_date DATE)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_day_start TIMESTAMPTZ;
  v_day_end TIMESTAMPTZ;
  v_winner RECORD;
  v_user users%ROWTYPE;
  v_new_bal NUMERIC(20,2);
  v_prize NUMERIC(20,2);
  v_winners JSONB := '[]'::jsonb;
  v_total NUMERIC(20,2) := 0;
  v_count INTEGER := 0;
BEGIN
  IF p_race_date IS NULL THEN
    RAISE EXCEPTION 'race date is required';
  END IF;

  v_day_start := p_race_date::timestamp AT TIME ZONE 'utc';
  v_day_end := v_day_start + interval '1 day';

  INSERT INTO public.daily_races (race_date) VALUES (p_race_date)
  ON CONFLICT (race_date) DO NOTHING;
  IF NOT FOUND THEN
    RETURN jsonb_build_object('ok', true, 'alreadySettled', true, 'raceDate', p_race_date);
  END IF;

  FOR v_winner IN
    WITH race_day AS (
      SELECT user_id, SUM(wagered) AS wagered, MAX(bet_at) AS last_bet_at
      FROM (
        SELECT user_id,
          COALESCE(
            NULLIF((metadata -> 'response' ->> 'betAmount')::numeric, 0),
            NULLIF((metadata -> 'response' -> 'result' ->> 'amount')::numeric, 0),
            CASE WHEN amount < 0 THEN ABS(amount) ELSE 0 END
          ) AS wagered,
          created_at AS bet_at
        FROM public.wallet_transactions
        WHERE type = 'bet_settled' AND created_at >= v_day_start AND created_at < v_day_end
        UNION ALL
        SELECT user_id, bet_amount, updated_at
        FROM public.game_rounds
        WHERE status = 'SETTLED' AND updated_at >= v_day_start AND updated_at < v_day_end
      ) candidates
      GROUP BY user_id
    )
    SELECT user_id, wagered, last_bet_at,
      ROW_NUMBER() OVER (ORDER BY wagered DESC, last_bet_at ASC, user_id ASC) AS rnk
    FROM race_day
    ORDER BY wagered DESC, last_bet_at ASC, user_id ASC
    LIMIT 3
  LOOP
    SELECT * INTO v_user FROM public.users WHERE id = v_winner.user_id FOR UPDATE;
    IF NOT FOUND THEN CONTINUE; END IF;

    v_prize := (ARRAY[5000.00, 3000.00, 2000.00])[v_winner.rnk];
    v_new_bal := round((v_user.balance + v_prize)::numeric, 2);

    UPDATE public.users SET balance = v_new_bal, updated_at = now() WHERE id = v_winner.user_id;
    INSERT INTO public.wallet_transactions (user_id, game, type, amount, balance_after, metadata)
    VALUES (
      v_winner.user_id,
      'bonus',
      'bonus',
      v_prize,
      v_new_bal,
      jsonb_build_object(
        'source', 'daily_race',
        'raceDate', p_race_date,
        'rank', v_winner.rnk,
        'wagered', round(v_winner.wagered, 2)
      )
    );
    INSERT INTO public.daily_race_winners (race_date, rank, user_id, wagered, prize)
    VALUES (p_race_date, v_winner.rnk, v_winner.user_id, round(v_winner.wagered, 2), v_prize);

    v_winners := v_winners || jsonb_build_object(
      'rank', v_winner.rnk,
      'userId', v_winner.user_id,
      'prize', v_prize
    );
    v_total := v_total + v_winner.wagered;
    v_count := v_count + 1;
  END LOOP;

  UPDATE public.daily_races
  SET total_wagered = round(v_total, 2), participant_count = v_count
  WHERE race_date = p_race_date;

  RETURN jsonb_build_object('ok', true, 'raceDate', p_race_date, 'winners', v_winners);
END;
$$;

